@then(parsers.parse('with HSI48 switched off, "{command}" fails with "{reason}", and HSI48 is switched on again even if that fails'))
def refused_with_hsi48_off(fw, command, reason):
    fw.clock.hsi48(False)
    try:
        expect_reason(fw, command, reason)
    finally:
        fw.clock.hsi48(True)


@then(
    parsers.parse(
        'with HSI48 switched off, the reads and statistics of the sync and async variants fail with "{reason}" and {count:d} bytes '
        "read with the hsem variant have {size:d} bytes, and HSI48 is switched on again even if that fails"
    )
)
def plain_variants_refused(fw, reason, count, size):
    fw.clock.hsi48(False)
    try:
        for line in ("rng.read 4", "rng.read 4 variant=async", "rng.stats 16", "rng.stats 16 variant=async"):
            expect_reason(fw, line, reason)
        assert len(fw.rng.read(count, variant="hsem").data) == size
    finally:
        fw.clock.hsi48(True)


@then(
    parsers.parse(
        "with semaphore 0 taken for process 1, the hsem variant's read of 4 bytes and statistics of 16 bytes fail with "
        '"{reason}", and the semaphore is released again even if that fails'
    )
)
def semaphore_0_refused(fw, reason):
    fw.hsem.take(0, procid=1)
    try:
        expect_reason(fw, "rng.read 4 variant=hsem", reason)
        expect_reason(fw, "rng.stats 16 variant=hsem", reason)
    finally:
        fw.hsem.release(0, procid=1)


@then(
    parsers.parse(
        "with semaphore 5 taken for process 1, {count:d} bytes read with the hsem variant report HSI48 on, the read with "
        'semaphore 5 locked fails with "{locked_reason}", and with HSI48 switched off the hsem variant\'s read fails with '
        '"{off_reason}", HSI48 switched on and the semaphore released again even if that fails'
    )
)
def semaphore_5_of_another_process(fw, count, locked_reason, off_reason):
    fw.hsem.take(5, procid=1)
    try:
        assert fw.rng.read(count, variant="hsem").hsi48 == 1
        expect_reason(fw, "rng.read 4 variant=hsem lock5=1", locked_reason)
        fw.clock.hsi48(False)
        try:
            expect_reason(fw, "rng.read 4 variant=hsem", off_reason)
        finally:
            fw.clock.hsi48(True)
    finally:
        fw.hsem.release(5, procid=1)


@then(
    parsers.parse(
        'with the flash stack "{state}", the hsem variant\'s read of {count:d} bytes fails with "{reason}" and {plain:d} bytes '
        'read without a variant have {size:d} bytes, and the flash stack is set to "{restored}" again even if that fails'
    )
)
def coordinated_flash_excludes_hsem(fw, state, count, reason, plain, size, restored):
    fw.flash.stack(state)
    try:
        expect_reason(fw, f"rng.read {count} variant=hsem", reason)
        assert len(fw.rng.read(plain).data) == size
    finally:
        fw.flash.stack(restored)
