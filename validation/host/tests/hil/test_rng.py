@then(
    parsers.parse("{count:d} bytes read with every variant of the board file in order and then in reverse order have {size:d} bytes each")
)
def variants_take_turns(fw, rng_cfg, count, size):
    variants = list(rng_cfg["variants"])
    for variant in variants + variants[::-1]:
        assert len(fw.rng.read(count, variant=variant).data) == size, variant


